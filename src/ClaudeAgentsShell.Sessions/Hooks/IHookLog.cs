using ClaudeAgentsShell.Domain;

namespace ClaudeAgentsShell.Sessions.Hooks;

/// <summary>
/// Журнал принятых хуков: одна строка на разобранное событие. Нужен, чтобы разбор случаев
/// неверной индикации был наблюдением хук-трафика, а не рассуждением по схеме (issue #1, пункт 4).
/// </summary>
public interface IHookLog
{
    /// <summary>
    /// Ставит событие в журнал. Возвращается сразу, не дожидаясь диска, и не бросает никогда:
    /// зовёт его поток приёма хуков, и ни задержка, ни сбой ввода-вывода на него
    /// перекладываться не должны.
    /// </summary>
    void Record(HookEvent hookEvent);
}
