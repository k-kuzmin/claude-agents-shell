namespace ClaudeAgentsShell.Sessions;

/// <summary>
/// Настройки слоя сессий. Значения по умолчанию соответствуют разделам 4.1 и 6.2 ТЗ.
/// </summary>
public sealed record SessionsOptions
{
    /// <summary>
    /// Дебаунс наблюдателя за веткой. Одна операция git трогает <c>.git</c> многократно
    /// (например, <c>HEAD.lock</c> и переименование поверх <c>HEAD</c>), поэтому события
    /// склеиваются в одно чтение.
    /// </summary>
    public TimeSpan GitBranchDebounce { get; init; } = TimeSpan.FromMilliseconds(250);

    /// <summary>
    /// Сколько символов транскрипта просматривается в поисках заголовка сессии, прежде чем
    /// чтение сдаётся. Заголовок не найден в пределах предела — вкладка остаётся
    /// с «новая сессия». Единица — символ UTF-16, а не байт; подробности ниже.
    /// </summary>
    /// <remarks>
    /// Величина считается в символах UTF-16, а не в байтах: подсчёт идёт по длине уже прочитанных
    /// строк. Замер ниже снят той же мерой, поэтому числа в таблице сопоставимы между собой,
    /// но на кириллическом транскрипте прочитанный объём в байтах примерно вдвое больше предела.
    /// <para>
    /// От горячего пути защищает не этот предел, а <c>TitleLookup</c> в координаторе состояний:
    /// он держит чтение не чаще нескольких раз за сессию и уводит его в поток пула. Предел решает
    /// другую задачу — сколько стоит одно такое чтение при <c>--resume</c> уже большого
    /// транскрипта. У новой сессии файл весит единицы килобайт, и предел там не стоит ничего.
    /// </para>
    /// <para>
    /// Значение выбрано замером на корпусе пользователя (778 транскриптов верхнего уровня,
    /// 670 МБ). Заголовка не имеют 21 файл — при любом пределе: слэш-команды отбрасываются
    /// правилом очистки, а строки с <c>tool_result</c> текстового блока не содержат.
    /// Собственная цена предела — сверх этих неизбежных:
    /// </para>
    /// <list type="bullet">
    ///   <item><description>256 КиБ — 79 файлов, одно чтение до 3,0 мс и 0,8 МБ;</description></item>
    ///   <item><description>1 МиБ — 52 файла, до 7,9 мс и 3,5 МБ;</description></item>
    ///   <item><description><b>4 МиБ — 7 файлов, до 13,4 мс и 8,4 МБ;</b></description></item>
    ///   <item><description>16 МиБ — 0 файлов, но уже 26,5 мс и 14,8 МБ: за коленом кривой.</description></item>
    /// </list>
    /// <para>
    /// Взято 4 МиБ: +5,5 мс и +5 МБ к одному чтению против мегабайта покупают настоящее имя
    /// вкладки 45 сессиям из 778. Деградация оставшихся до «новая сессия» разрешена разделом 7
    /// CLAUDE.md прямо — формат <c>.jsonl</c> считается нестабильным.
    /// </para>
    /// <para>
    /// Хвост аллокаций пределом не лечится: он задаётся самой длинной строкой файла (в корпусе
    /// до 1 220 885 символов, ~2,4 МБ на строку), а она аллоцируется целиком ещё в
    /// <c>ReadLineAsync</c>, до всякого разбора. Поэтому худшие аллокации почти не зависят
    /// от предела, и «не парсить длинные строки» ничего бы не сэкономило.
    /// </para>
    /// </remarks>
    public long TranscriptScanLimit { get; init; } = 4 * 1024 * 1024;
}
