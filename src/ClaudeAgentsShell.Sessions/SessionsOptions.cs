namespace ClaudeAgentsShell.Sessions;

/// <summary>
/// Настройки слоя сессий. Значения по умолчанию соответствуют разделам 4.1 и 6.2 ТЗ.
/// </summary>
public sealed record SessionsOptions
{
    /// <summary>
    /// Дебаунс наблюдателя за веткой. Одна операция git трогает <c>.git</c> многократно
    /// (например, <c>HEAD.lock</c> и переименование поверх <c>HEAD</c>), поэтому события
    /// склеиваются в одно чтение.
    /// </summary>
    public TimeSpan GitBranchDebounce { get; init; } = TimeSpan.FromMilliseconds(250);

    /// <summary>
    /// Сколько символов транскрипта просматривается в поисках заголовка сессии, прежде чем
    /// чтение сдаётся. Заголовок не найден в пределах предела — вкладка остаётся
    /// с «новая сессия».
    /// </summary>
    /// <remarks>
    /// Предел нужен потому, что заголовок ищется на горячем пути: он перечитывается по хуку
    /// <c>Stop</c>, то есть на каждый ответ агента, а кэш разбора по ключу «путь, время, размер»
    /// в этот момент гарантированно промахивается — файл только что дописан. Без предела один
    /// проход по транскрипту в 7,7 МБ стоит около 42 мс процессорного времени и 21 МБ аллокаций,
    /// и в корпусе встречаются файлы до 54 МБ.
    /// <para>
    /// Мегабайт ограничивает один проход примерно пятью-шестью миллисекундами и парой мегабайт
    /// аллокаций. Плата известна и принята: транскрипт, где первое сообщение пользователя лежит
    /// глубже предела (в замере встретился файл, у которого заголовок нашёлся на 9,3 МБ),
    /// деградирует до «новая сессия». Раздел 7 CLAUDE.md разрешает это прямо, объявляя формат
    /// <c>.jsonl</c> нестабильным.
    /// </para>
    /// </remarks>
    public long TranscriptScanLimit { get; init; } = 1024 * 1024;
}
