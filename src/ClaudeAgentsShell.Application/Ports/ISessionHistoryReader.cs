using ClaudeAgentsShell.Domain;

namespace ClaudeAgentsShell.Application.Ports;

/// <summary>
/// Читает историю сессий Claude Code из <c>~/.claude/projects/&lt;slug&gt;</c>.
/// Файлы только читаются: ни записи, ни удаления. Любой сбой разбора деградирует
/// до «имя файла и дата» и не роняет приложение.
/// </summary>
public interface ISessionHistoryReader
{
    /// <summary>
    /// Сводки по сессиям рабочего каталога, от свежих к старым.
    /// Каталога нет — пустой список, это не ошибка.
    /// </summary>
    Task<IReadOnlyList<SessionSummary>> ReadAsync(string workingDirectory, CancellationToken cancellationToken);

    /// <summary>
    /// Сводка по одной известной сессии. Нужна, когда хук <c>SessionStart</c> уже принёс
    /// <c>session_id</c> и вкладке требуется заголовок из первого сообщения пользователя.
    /// </summary>
    /// <returns>
    /// <c>null</c> — файла ещё нет или его не удалось открыть: спросить позже имеет смысл.
    /// Сводка с <c>Title: null</c> — файл прочитан, но заголовка в нём нет: спрашивать снова
    /// бессмысленно, вкладка остаётся с «новая сессия».
    /// </returns>
    /// <remarks>
    /// Различать эти два исхода обязательно. Вызывающий повторяет попытку, пока заголовка нет,
    /// а транскрипт растёт весь сеанс — без признака «искали и не нашли» повтор превращается
    /// в перечитывание многомегабайтного файла на каждый ответ агента. На корпусе пользователя
    /// заголовка не дают 2,7 % файлов, так что это не редкий край, а штатный случай.
    /// <para>
    /// Глубина чтения обязана быть ограничена: реализация дочитывает до заголовка, но не дальше
    /// своего предела. Деградация до «имя файла и дата» разрешена разделом 7 CLAUDE.md —
    /// формат <c>.jsonl</c> считается нестабильным.
    /// </para>
    /// </remarks>
    Task<SessionSummary?> ReadOneAsync(string workingDirectory, string sessionId, CancellationToken cancellationToken);
}
