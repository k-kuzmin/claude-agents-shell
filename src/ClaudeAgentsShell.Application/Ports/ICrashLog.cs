namespace ClaudeAgentsShell.Application.Ports;

/// <summary>
/// Журнал сбоев: одна запись на необработанное исключение. Пишут сюда только глобальные
/// обработчики приложения — это не система логирования и не место для трассировки сценариев.
/// </summary>
public interface ICrashLog
{
    /// <summary>
    /// Записывает сбой: время, источник, тип, сообщение и полный стек, включая внутренние
    /// исключения.
    /// <para>
    /// Не бросает никогда — ни при недоступном диске, ни при неверном аргументе: зовут её
    /// из обработчика падения, где второе исключение убивает процесс без следа.
    /// </para>
    /// </summary>
    /// <param name="source">Откуда пришёл сбой: имя обработчика, а не текст для пользователя.</param>
    /// <param name="exception">Само исключение.</param>
    /// <returns>Путь к файлу журнала или <c>null</c>, если записать не удалось.</returns>
    string? Write(string source, Exception exception);
}
