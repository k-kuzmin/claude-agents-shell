namespace ClaudeAgentsShell.Application.Ports;

/// <summary>
/// Сообщает, что история сессий рабочего каталога могла измениться: в
/// <c>~/.claude/projects/&lt;slug&gt;</c> появился, изменился или исчез <c>.jsonl</c>.
/// Только <c>FileSystemWatcher</c>, без периодического опроса (раздел 5.2 ТЗ).
/// </summary>
/// <remarks>
/// Каталога истории может ещё не быть — проект без единой сессии. Реализация тогда
/// ждёт его появления и начинает сообщать об изменениях, как только он создан.
/// Файлы при этом только наблюдаются: ни записи, ни создания каталога.
/// </remarks>
public interface ISessionHistoryWatcher
{
    /// <summary>
    /// Начинает наблюдение за историей рабочего каталога.
    /// </summary>
    /// <param name="workingDirectory">Рабочий каталог проекта, как у <see cref="ISessionHistoryReader.ReadAsync"/>.</param>
    /// <param name="changed">
    /// Вызывается из пула потоков, когда список или содержимое транскриптов могли измениться.
    /// Пачка событий файловой системы сворачивается в один вызов; что именно изменилось,
    /// не сообщается — вызывающий перечитывает список через <see cref="ISessionHistoryReader"/>,
    /// а кэш разбора не даёт перечитывать неизменные файлы.
    /// </param>
    /// <returns>Подписка; её освобождение останавливает наблюдение и гарантирует, что новых вызовов не будет.</returns>
    IDisposable Watch(string workingDirectory, Action changed);
}
