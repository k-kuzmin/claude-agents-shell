namespace ClaudeAgentsShell.Application.Ports;

/// <summary>
/// Открывает ссылку в браузере по умолчанию. Существует ради запрета из раздела 3
/// CLAUDE.md: <c>Process.*</c> во ViewModel и в код-бихайде окна недопустим.
/// </summary>
/// <remarks>
/// Отдельный порт, а не второй метод <see cref="IShellLauncher"/>: у открытия каталога
/// в проводнике и у открытия ссылки нет общих потребителей — каталог нужен контекстному
/// меню проекта, ссылка нужна сообщению об отсутствующем WebView2 Runtime. Общий интерфейс
/// заставил бы каждую реализацию отвечать за обе роли, а это ровно тот
/// «интерфейс-помойка», который запрещён разделом 3 CLAUDE.md (ISP). Проверки у методов
/// тоже разные: каталог проверяется на существование, ссылка — на схему.
/// </remarks>
public interface IUrlLauncher
{
    /// <summary>
    /// Открывает ссылку в браузере по умолчанию. Разрешены только схемы <c>http</c>
    /// и <c>https</c>: передавать в оболочку произвольную строку нельзя.
    /// </summary>
    /// <returns>
    /// <c>false</c>, если ссылка негодна или открыть её не удалось, — без исключения:
    /// окно с сообщением об ошибке не должно падать само.
    /// </returns>
    Task<bool> OpenUrlAsync(string url, CancellationToken cancellationToken);
}
