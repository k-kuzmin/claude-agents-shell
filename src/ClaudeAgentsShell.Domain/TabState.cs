namespace ClaudeAgentsShell.Domain;

/// <summary>
/// Состояние вкладки. Источник — хуки Claude Code, а не разбор вывода.
/// Если хуки не сработали, состояние остаётся <see cref="Unknown"/> — это допустимая деградация.
/// </summary>
public enum TabState
{
    /// <summary>Маркера нет: хуки не подключились или сессия запущена мимо приложения.</summary>
    Unknown = 0,

    /// <summary>Простаивает: сессия живёт, но агент не работал и ввода не ждёт.</summary>
    Idle = 1,

    /// <summary>Работает: агент занят.</summary>
    Busy = 2,

    /// <summary>Ждёт ввода: агент закончил ответ (хук <c>Stop</c>) и пользователь ещё не ответил.</summary>
    AwaitingInput = 3,

    /// <summary>
    /// Ждёт собственную фоновую работу: ход агента закончился, но у сессии остались
    /// незавершённые сабагенты, и она продолжится сама, без участия человека.
    /// </summary>
    /// <remarks>
    /// Четвёртого состояния в разделе 5.3 ТЗ нет — оно добавлено по решению пользователя.
    /// Без него запуск фоновых сабагентов выглядел как «ждёт ввода»: точка загоралась,
    /// пользователь шёл на вкладку, а печатать там было нечего.
    /// <para>
    /// В счётчик «N ждёт ввода» это состояние **не** входит: оно означает ровно обратное —
    /// от человека сейчас ничего не нужно.
    /// </para>
    /// <para>
    /// Покрывает только сабагентов: у Claude Code есть парные хуки <c>SubagentStart</c> и
    /// <c>SubagentStop</c>, а для фоновых команд <c>Bash</c> с <c>run_in_background</c> хуков
    /// нет вовсе. Сессия, ждущая только фоновую команду, по-прежнему покажет «ждёт ввода».
    /// </para>
    /// </remarks>
    BackgroundWork = 4,
}
