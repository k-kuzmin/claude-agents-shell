namespace ClaudeAgentsShell.App.Services;

/// <summary>
/// Признак «гашение окна началось». Взводится один раз и назад не снимается.
/// <para>
/// Нужен глобальным обработчикам исключений: после того как окно спрятано, показывать
/// модальное окно об ошибке некому и негде — оно всплывёт поверх пустого места, без
/// владельца, и не даст процессу уйти, пока его не закроют. Сбой в потоке интерфейса
/// приходит сюда не теоретически: завершение псевдоконсолей во время гашения поднимает
/// события, обработчики которых доигрываются в диспетчере уже после <c>Hide</c>.
/// </para>
/// <para>
/// Отдельный объект вместо свойства окна — чтобы <c>App</c> и <see cref="CrashReporter"/>
/// знали факт «гасимся», не зная ничего про окно и не заводя статики. Взводит его тот,
/// кто этим фактом и распоряжается, — <c>WindowShutdownSequence</c>.
/// </para>
/// </summary>
public sealed class ShutdownSignal
{
    // Читается с любого потока: сбой приходит и из пула, и из финализатора.
    private int _started;

    /// <summary>Гашение начато — окна пользователю больше не показываются.</summary>
    public bool IsShuttingDown => Volatile.Read(ref _started) != 0;

    /// <summary>Отмечает начало гашения. Повторный вызов ничего не меняет.</summary>
    public void MarkStarted() => Volatile.Write(ref _started, 1);
}
