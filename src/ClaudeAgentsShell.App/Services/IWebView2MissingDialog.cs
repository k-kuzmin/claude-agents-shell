namespace ClaudeAgentsShell.App.Services;

/// <summary>
/// Окно «не установлен движок терминалов» (раздел 8 ТЗ): объяснение и ссылка на установщик
/// вместо стек-трейса.
/// </summary>
/// <remarks>
/// Порт уровня оболочки: модальное окно — WPF-специфика. Существует, чтобы главное окно
/// не собирало у себя ViewModel и разметку чужого окна, а просто говорило «покажи это».
/// </remarks>
public interface IWebView2MissingDialog
{
    /// <summary>
    /// Показывает окно поверх главного и ждёт, пока пользователь его закроет.
    /// Ответа нет: после этого разговора приложению остаётся только завершиться.
    /// </summary>
    /// <param name="failure">Сбой, с которым не поднялась страница терминалов.</param>
    void Show(Exception failure);
}
